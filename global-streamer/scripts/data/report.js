'use strict';
/* Jana docs/ANALISIS-MLBB.md daripada data yang dikumpul. Guna: node scripts/data/report.js */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', '..');
const S = JSON.parse(fs.readFileSync(path.join(dir, 'renderer', 'data', 'mlbb-static.json'), 'utf8'));
const M = JSON.parse(fs.readFileSync(path.join(dir, 'renderer', 'data', 'meta.json'), 'utf8'));

const by = (arr, f) => arr.reduce((m, x) => { [].concat(f(x)).forEach((k) => { (m[k] = m[k] || []).push(x); }); return m; }, {});
const LANE = { gold: 'Gold Lane', mid: 'Mid Lane', exp: 'EXP Lane', jungle: 'Jungle', roam: 'Roam' };
const pct = (x) => (x * 100).toFixed(1) + '%';
const out = [];
const w = (s = '') => out.push(s);

w('# Analisis MLBB (dijana automatik)');
w();
w(`Dijana oleh \`scripts/data/report.js\` daripada data yang dikumpul pada **${S.generated.slice(0, 10)}** (hero/item/emblem) dan **${M.generated.slice(0, 16).replace('T', ' ')} UTC** (meta tournament).`);
w('Jangan edit tangan. Jalankan semula pengumpul kemudian laporan ini.');
w();
w('## Sumber dan lesen');
w('* Hero, item, emblem: [Mobile Legends Wiki (Fandom)](https://mobile-legends.fandom.com), CC-BY-SA 3.0. Dikumpul melalui MediaWiki API awam.');
w('* Statistik tournament: [Liquipedia Mobile Legends](https://liquipedia.net/mobilelegends), CC-BY-SA 3.0. Dikumpul melalui MediaWiki API awam dengan User-Agent yang jelas dan jeda 30 saat setiap halaman (had Liquipedia).');
w('* **API tidak didokumenkan Moonton TIDAK digunakan.** Tiada scraping tapak rasmi.');
w('* Atribusi dipaparkan dalam app (tab Meta, Draft, Item, Emblem dan widget Meta Tournament).');
w();
w('## Hero');
w(`Jumlah: **${S.heroes.length}** (hero terbaharu: ${S.heroes.slice(-3).map((h) => h.name + (h.released ? ' ' + h.released : '')).join(', ')}).`);
w();
w('| Peranan | Bilangan |');
w('|---|---|');
const roles = by(S.heroes, (h) => h.roles);
Object.keys(roles).sort().forEach((r) => w(`| ${r} | ${roles[r].length} |`));
w();
w('| Lane | Bilangan | Hero |');
w('|---|---|---|');
const lanes = by(S.heroes, (h) => h.lanes);
['gold', 'mid', 'exp', 'jungle', 'roam'].forEach((l) => w(`| ${LANE[l]} | ${(lanes[l] || []).length} | ${(lanes[l] || []).map((h) => h.name).join(', ')} |`));
w();
w('## Item');
const shop = S.items.filter((i) => i.price);
const cats = by(shop, (i) => (/Potion$/i.test(i.name) ? 'potion' : i.tabs[0]));
w(`Item kedai: **${shop.length}**.`);
w();
w('| Kategori | Bilangan | Item |');
w('|---|---|---|');
Object.keys(cats).forEach((c) => w(`| ${c} | ${cats[c].length} | ${cats[c].map((i) => i.name + ' (' + i.price + ')').join(', ')} |`));
w();
w('## Emblem');
w('| Set | Atribut | Talent biasa | Talent teras |');
w('|---|---|---|---|');
S.emblems.forEach((e) => w(`| ${e.name} | ${e.attributes.map((a) => a.stat + ' ' + a.value).join(', ')} | ${e.standard.flat().map((t) => t.name).join(', ')} | ${e.core.map((t) => t.name).join(', ')} |`));
w();
w('## Meta tournament');
w('| Tournament | Game | Hero | Status |');
w('|---|---|---|---|');
M.tournaments.forEach((t) => w(`| ${t.label} | ${t.games} | ${Object.keys(t.heroes).length} | ${t.live ? 'LIVE' : 'tamat'} (diambil ${t.fetched.slice(0, 16).replace('T', ' ')} UTC) |`));
w();
// agregat tier != history
const agg = {};
let games = 0;
M.tournaments.filter((t) => t.tier !== 'history').forEach((t) => {
  games += t.games;
  Object.entries(t.heroes).forEach(([n, s]) => { const a = agg[n] || (agg[n] = { n, p: 0, w: 0, b: 0 }); a.p += s.p; a.w += s.w; a.b += s.b; });
});
const list = Object.values(agg);
const row = (a, i) => `| ${i + 1} | ${a.n} | ${a.p} | ${pct(a.p / games)} | ${a.p ? pct(a.w / a.p) : '-'} | ${a.b} | ${pct(a.b / games)} |`;
w(`Skop "Terkini" (semua kecuali sejarah): **${games} game**.`);
w();
w('### Top pick');
w('| # | Hero | Pick | Pick% | WR | Ban | Ban% |');
w('|---|---|---|---|---|---|---|');
list.sort((a, b) => b.p - a.p).slice(0, 10).forEach((a, i) => w(row(a, i)));
w();
w('### Top ban');
w('| # | Hero | Pick | Pick% | WR | Ban | Ban% |');
w('|---|---|---|---|---|---|---|');
list.sort((a, b) => b.b - a.b).slice(0, 10).forEach((a, i) => w(row(a, i)));
w();
w('### Kadar menang tertinggi (min. 15 pick)');
w('| # | Hero | Pick | Pick% | WR | Ban | Ban% |');
w('|---|---|---|---|---|---|---|');
list.filter((a) => a.p >= 15).sort((a, b) => b.w / b.p - a.w / a.p).slice(0, 10).forEach((a, i) => w(row(a, i)));
w();
w('## Had data');
w('* Liquipedia memaparkan hanya **5 teratas** untuk "Played With" dan "Played Against" bagi setiap hero, jadi padanan/counter dalam cadangan adalah separa dan menggunakan pemberat awal (sampel kecil tidak terlalu berpengaruh).');
w('* Statistik hanya berubah selepas game selesai. Kekerapan kemas kini bergantung pada jadual pengumpul (lihat `.github/workflows/meta-sync.yml`) dan penyiaran ke Hosting.');
w('* Peranan/lane ialah cadangan wiki, bukan peranan tetap; pro-player boleh menggunakan hero di lane lain.');
w('* Cadangan pick/ban ialah pengiraan statistik yang boleh dijelaskan (kadar menang, kehadiran, counter, padanan, lane kosong). Ia bukan jaminan kemenangan.');

fs.writeFileSync(path.join(dir, 'docs', 'ANALISIS-MLBB.md'), out.join('\n') + '\n');
console.log('docs/ANALISIS-MLBB.md', out.length, 'baris');
